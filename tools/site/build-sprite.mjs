// Builds site/assets/icons.svg, the Lucide sprite used by the GitHub Pages
// site, from the @lucide/svelte package the web app already depends on.
// Run after `npm --prefix web ci`:  node tools/site/build-sprite.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const pkg = path.join(repo, 'web', 'node_modules', '@lucide', 'svelte');
const out = path.join(repo, 'site', 'assets', 'icons.svg');

const icons = [
  'archive', 'at-sign', 'bell-ring', 'bot', 'check-check', 'circle-check', 'container',
  'cpu', 'download', 'external-link', 'eye-off', 'file-image', 'hash', 'key-round',
  'laptop', 'lock', 'message-circle', 'messages-square', 'monitor', 'moon', 'paperclip',
  'pin', 'plug', 'qr-code', 'radar', 'reply', 'rotate-ccw', 'search', 'server',
  'shield-check', 'smartphone', 'face-slightly-smiling', 'sun', 'terminal', 'trash', 'users',
  'webhook', 'wifi-off', 'x', 'zap',
];

const { version } = JSON.parse(readFileSync(path.join(pkg, 'package.json'), 'utf8'));

const attrs = (o) =>
  Object.entries(o)
    .map(([k, v]) => `${k}="${String(v).replace(/"/g, '&quot;')}"`)
    .join(' ');

const symbols = icons.map((name) => {
  const src = readFileSync(path.join(pkg, 'dist', 'icons', `${name}.svelte`), 'utf8');
  const match = src.match(/const iconData = (\{.*?\});\n/s);
  if (!match) throw new Error(`no iconData in ${name}.svelte`);
  const { node } = JSON.parse(match[1]);
  const body = node.map(([tag, a]) => `<${tag} ${attrs(a)} />`).join('');
  return `  <symbol id="i-${name}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${body}</symbol>`;
});

writeFileSync(
  out,
  `<!-- Lucide v${version} (ISC) — generated by tools/site/build-sprite.mjs; do not edit -->\n` +
    `<svg xmlns="http://www.w3.org/2000/svg" style="display:none">\n${symbols.join('\n')}\n</svg>\n`,
);
console.log(`wrote ${icons.length} icons to ${path.relative(repo, out)}`);
